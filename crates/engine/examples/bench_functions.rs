//! The function catalogue: how long each worksheet function takes on real data.
//!
//! `cargo run --release -p cella-engine --example bench_functions -- [rows...] [--only=NAME,...]
//! [--json-out=PATH] [--repeat=N] [--max-ms=N]`
//!
//! Every registered function gets one call, entered into a fresh session holding a `rows`-row
//! workbook, at two argument scales: `small` (ten-row ranges, scalar literals) and `whole` (the
//! whole column). The measured number is the `cell.set` that enters the formula and evaluates it —
//! the wait between typing a formula and seeing its value — and the row says what the call was and
//! what came back, so "this function is slow" can always be checked against a formula a person
//! could type.
//!
//! The calls live in [`xtask/bench-functions.txt`](../../../xtask/bench-functions.txt), one per
//! line: name, tab, template, optional tab, note. A template uses `$R` (the id column), `$R2`
//! (quantities), `$R3` (prices), `$RT` (item names), `$E` (regions), `$F`/`$RD` (dates), `$T` (a
//! two-column text-key table), `$TN` (a three-column numeric-key table), `$KG` (the key column),
//! `$RH` (the value column), `$K`/`$KN` (a key that exists in the table) and `$DATE` (a date
//! serial); at the small scale every range token becomes ten rows, at the whole scale the whole
//! column. A template with no token is scalar and is measured once, as the `scalar` scale.
//!
//! `$RS`/`$TS` are the value column and the timeline of a series the FORECAST.ETS family fits, and
//! `$LS` is that series' last point: they stop at [`SERIES_CAP`] rows, because the engine refuses a
//! longer series (a whole column of a million rows is a `#NUM!`). The note a line can carry is how a
//! row whose call is not what its shape suggests says so on the page.
//!
//! Like the command catalogue, this is deliberately outside `cargo xtask ci`: it is a release
//! build against a million rows, and the page it feeds ([`docs/performance-functions.md`]) is
//! regenerated by `cargo xtask bench-functions`.

#![allow(clippy::disallowed_methods)] // native-only catalogue; the clock is the measurement

use std::process::ExitCode;
use std::time::Instant;

use cella_engine::{DocState, EngineError, Session};
use serde_json::{Value as Json, json};

/// Row counts measured when none are given: the two sizes the rest of the bench uses.
const DEFAULT_ROWS: [usize; 2] = [100_000, 1_000_000];
/// Largest row count this harness accepts (an argument-derived size, so it is capped).
const MAX_ROWS: usize = 5_000_000;
/// Rows per `range.setValues` call when filling the workbook.
const CHUNK: usize = 10_000;
/// The cell the formula goes into.
const TARGET: &str = "Z1";
/// The two argument scales.
const SCALES: [&str; 2] = ["small", "whole"];
/// Rows a `small`-scale range covers.
const SMALL_ROWS: usize = 10;
/// The four regions a data row carries, so criteria and grouping functions have values to find.
const REGIONS: [&str; 4] = ["North", "South", "East", "West"];
/// Longest series the FORECAST.ETS family accepts — `cella_functions::ets::MAX_POINTS`, restated
/// here because the example measures a call a person could type, not the model behind it. A whole
/// column of a million rows is more than this, so those four functions are fitted at the cap.
const SERIES_CAP: usize = 200_000;

/// The calls, one per function (edited by hand, checked by `cargo xtask bench-functions --check`).
const CALLS: &str = include_str!("../../../xtask/bench-functions.txt");

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("bench_functions: {e}");
            ExitCode::FAILURE
        }
    }
}

struct Args {
    rows: Vec<usize>,
    only: Option<Vec<String>>,
    json_out: Option<String>,
    repeat: usize,
    max_ms: f64,
    calls: Option<String>,
}

/// One line of the table.
#[derive(Clone, Debug)]
struct Call {
    name: String,
    template: String,
    /// The function's documented answer is an error (CUBE functions without a connection,
    /// `NA`, `WEBSERVICE` with no network), so an error row is the right row.
    expect_error: bool,
    /// Why the call is what it is, when the shape of the sheet says otherwise.
    note: Option<String>,
}

/// One measurement.
#[derive(Clone, Debug)]
struct Measurement {
    name: String,
    template: String,
    rows: usize,
    scale: &'static str,
    ms: f64,
    /// `ok` (a value came back), `error` (the function answered with a `#` error) or `refused`
    /// (entering the formula failed: the call does not parse or its arity is wrong).
    outcome: &'static str,
    /// Whether that outcome is the documented answer (see [`Call::expect_error`]).
    expected: bool,
    detail: Option<String>,
    /// The call's own note (see [`Call::note`]), printed in the page's note column.
    note: Option<String>,
}

fn usage() -> String {
    "usage: bench_functions [rows...] [--rows=N[,N...]] [--only=NAME[,NAME...]] [--json-out=PATH]
       [--repeat=N] [--max-ms=N] [--calls=PATH] [--list]

Times every worksheet function once, at 100k and 1M rows, with its arguments near the cursor
(`small`, ten rows) and over the whole used area (`whole`). Writes nothing; the page is
`cargo xtask bench-functions`. The calls come from xtask/bench-functions.txt.
"
    .to_string()
}

fn parse_args(args: &[String]) -> Result<Args, String> {
    let mut rows = Vec::new();
    let mut only = None;
    let mut json_out = None;
    let mut repeat = 1usize;
    let mut max_ms = 2_000.0;
    let mut calls = None;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        let (flag, inline) = match a.split_once('=') {
            Some((f, v)) => (f, Some(v)),
            None => (a.as_str(), None),
        };
        let value = |it: &mut std::slice::Iter<'_, String>| match inline {
            Some(v) => Ok(v.to_string()),
            None => it.next().cloned().ok_or_else(|| format!("{flag} needs a value")),
        };
        match flag {
            "-h" | "--help" => {
                print!("{}", usage());
                return Err(String::new());
            }
            "--list" => {
                let text = match &calls {
                    Some(p) => std::fs::read_to_string(p).map_err(|e| format!("{p}: {e}"))?,
                    None => CALLS.to_string(),
                };
                for call in parse_calls(&text)? {
                    println!("{}\t{}", call.name, call.template);
                }
                return Err(String::new());
            }
            "--json-out" => json_out = Some(value(&mut it)?),
            "--calls" => calls = Some(value(&mut it)?),
            "--rows" => {
                for r in value(&mut it)?.split(',') {
                    rows.push(rows_of(r)?);
                }
            }
            "--only" => {
                let list = value(&mut it)?;
                let names: Vec<String> = list.split(',').map(|s| s.trim().to_ascii_uppercase()).filter(|s| !s.is_empty()).collect();
                if names.is_empty() {
                    return Err("--only needs at least one function name".to_string());
                }
                only = Some(names);
            }
            "--repeat" => {
                repeat = value(&mut it)?.parse::<usize>().map_err(|_| "--repeat must be a number".to_string())?;
                if repeat == 0 || repeat > 5 {
                    return Err("--repeat must be 1..=5".to_string());
                }
            }
            "--max-ms" => {
                max_ms = value(&mut it)?.parse::<f64>().map_err(|_| "--max-ms must be a number".to_string())?;
                if !max_ms.is_finite() || max_ms <= 0.0 {
                    return Err("--max-ms must be positive".to_string());
                }
            }
            other => return Err(format!("unknown option `{other}`\n{}", usage())),
        }
    }
    if rows.is_empty() {
        rows.extend(DEFAULT_ROWS);
    }
    Ok(Args { rows, only, json_out, repeat, max_ms, calls })
}

fn rows_of(text: &str) -> Result<usize, String> {
    let rows = text.trim().parse::<usize>().map_err(|_| format!("`{text}` is not a row count"))?;
    if !(SMALL_ROWS + 1..=MAX_ROWS).contains(&rows) {
        return Err(format!("row count must be {}..={MAX_ROWS}, got {rows}", SMALL_ROWS + 1));
    }
    Ok(rows)
}

fn err(e: impl std::fmt::Display) -> String {
    e.to_string()
}

fn run() -> Result<(), String> {
    let args = match parse_args(&std::env::args().skip(1).collect::<Vec<_>>()) {
        Ok(a) => a,
        // `--list` and `--help` already printed, and neither is a failure.
        Err(e) if e.is_empty() => return Ok(()),
        Err(e) => return Err(e),
    };
    if cfg!(debug_assertions) {
        eprintln!("bench_functions: this is a debug build — the numbers are not comparable (use --release)");
    }
    let text = match &args.calls {
        Some(p) => std::fs::read_to_string(p).map_err(|e| format!("{p}: {e}"))?,
        None => CALLS.to_string(),
    };
    let calls: Vec<Call> =
        parse_calls(&text)?.into_iter().filter(|c| args.only.as_ref().is_none_or(|names| names.iter().any(|n| n == &c.name))).collect();
    if calls.is_empty() {
        return Err("no function matched".to_string());
    }
    let mut out: Vec<Measurement> = Vec::new();
    let mut floors: Vec<(usize, f64)> = Vec::new();
    for &rows in &args.rows {
        eprintln!("bench_functions: preparing {rows} rows");
        let base = prepare(rows)?;
        // The floor: what entering a formula that does nothing costs at this size, which is the
        // session's undo snapshot and the recalculation bookkeeping rather than the function. Every
        // scalar row is mostly this, so the page prints it once and the reader can subtract it.
        let nothing = Call { name: "(floor)".to_string(), template: "1+1".to_string(), expect_error: false, note: None };
        let floor = measure(&base, &nothing, rows, "scalar")?.ms;
        eprintln!("bench_functions: {rows} rows — the floor is {floor:.2} ms (entering `=1+1`)");
        floors.push((rows, floor));
        eprintln!("bench_functions: {rows} rows — {} calls", calls.len());
        for call in &calls {
            let scalar = !has_token(&call.template);
            let scales: Vec<&'static str> = if scalar { vec!["scalar"] } else { SCALES.to_vec() };
            for scale in scales {
                let mut best: Option<Measurement> = None;
                for pass in 0..args.repeat {
                    if args.repeat > 1 {
                        eprintln!("bench_functions: {rows} rows — {} ({scale}), pass {} of {}", call.name, pass + 1, args.repeat);
                    } else {
                        eprintln!("bench_functions: {rows} rows — {} ({scale})", call.name);
                    }
                    let m = measure(&base, call, rows, scale)?;
                    if best.as_ref().is_none_or(|b| m.ms < b.ms) {
                        best = Some(m);
                    }
                }
                if let Some(m) = best {
                    if m.ms > args.max_ms {
                        eprintln!(
                            "bench_functions: {} at {scale} took {:.0} ms (over --max-ms), so this call is not measured at a larger scale",
                            m.name, m.ms
                        );
                    }
                    out.push(m);
                }
            }
        }
    }
    if let Some(path) = &args.json_out {
        let doc = serde_json::to_string_pretty(&report(&args, &out, &floors)).map_err(err)?;
        std::fs::write(path, doc).map_err(|e| format!("{path}: {e}"))?;
        eprintln!("bench_functions: wrote {path}");
    }
    print!("{}", render(&out));
    Ok(())
}

/// Whether a template has a scale-dependent token.
fn has_token(template: &str) -> bool {
    [
        "$R2", "$R3", "$R", "$RT", "$RD", "$TN", "$T", "$KG", "$RH", "$E", "$F", "$KN", "$K", "$DATE", "$CR", "$CK", "$HT", "$Y", "$LAST", "$RS",
        "$TS", "$LS",
    ]
    .iter()
    .any(|t| template.contains(t))
}

/// The call table: `name<TAB>template[<TAB>error]`, `#` comments and blank lines ignored.
fn parse_calls(text: &str) -> Result<Vec<Call>, String> {
    let mut calls = Vec::new();
    for (n, line) in text.lines().enumerate() {
        let line = line.trim_end();
        if line.trim().is_empty() || line.trim_start().starts_with('#') {
            continue;
        }
        let mut parts = line.split('\t');
        let name = parts.next().unwrap_or("").trim();
        let template = match parts.next() {
            Some(t) => t.trim(),
            None => return Err(format!("line {}: `{line}` has no template", n + 1)),
        };
        if name.is_empty() || template.is_empty() {
            return Err(format!("line {}: `{line}` is not `name<TAB>template`", n + 1));
        }
        let extra = parts.next().map(str::trim).unwrap_or("");
        let expect_error = extra == "error";
        let note = (!extra.is_empty() && !expect_error).then(|| extra.to_string());
        calls.push(Call { name: name.to_string(), template: template.to_string(), expect_error, note });
    }
    Ok(calls)
}

/// Substitute the tokens for the given scale. Longest token first, so `$R2` is not read as `$R`.
fn expand(template: &str, rows: usize, scale: &str) -> String {
    let small = scale == "small";
    let last = if small { SMALL_ROWS + 1 } else { rows };
    // A series stops at the cap: the FORECAST.ETS family refuses a longer timeline, and a template
    // that asked for the whole column would be a row with no number at every large size.
    let series = if small { SMALL_ROWS + 1 } else { rows.min(SERIES_CAP + 1) };
    let mut s = template.to_string();
    // Column letters of the prepared workbook: A id, B qty, C price, D item, E region, F date,
    // G key, H value.
    let subs: [(&str, String); 22] = [
        ("$RS", format!("B2:B{series}")),
        ("$TS", format!("A2:A{series}")),
        ("$LS", format!("{series}")),
        ("$R3", format!("C2:C{last}")),
        ("$R2", format!("B2:B{last}")),
        ("$RT", format!("D2:D{last}")),
        ("$RD", format!("F2:F{last}")),
        ("$TN", format!("A1:C{last}")),
        ("$KG", format!("G2:G{last}")),
        ("$RH", format!("H2:H{last}")),
        ("$R", format!("A2:A{last}")),
        ("$T", format!("G1:H{last}")),
        ("$E", format!("E2:E{last}")),
        ("$F", format!("F2:F{last}")),
        ("$CR", "J1:J2".to_string()),
        ("$CK", "K1:K2".to_string()),
        ("$HT", "M1:P2".to_string()),
        ("$Y", "Y1".to_string()),
        ("$KN", format!("{}", if small { 7 } else { rows / 2 })),
        ("$DATE", "46317".to_string()),
        ("$K", format!("\"K{:06}\"", if small { 7 } else { rows / 2 })),
        ("$LAST", format!("{}", if small { SMALL_ROWS + 1 } else { rows })),
    ];
    for (token, value) in subs {
        s = s.replace(token, &value);
    }
    s
}

/// The workbook every function starts from: a header row and `rows - 1` data rows of eight
/// columns — a number, a quantity, a price, an item name, a region, a date, a key and a value.
fn prepare(rows: usize) -> Result<DocState, String> {
    let mut s = Session::new();
    s.new_workbook();
    s.execute("range.setValues", json!({"range": "A1", "values": [["Id", "Qty", "Price", "Item", "Region", "Date", "Key", "Value"]]}))
        .map_err(err)?;
    let data_rows = rows.saturating_sub(1);
    let mut r = 0;
    while r < data_rows {
        let n = CHUNK.min(data_rows - r);
        let values: Vec<Json> = (0..n)
            .map(|i| {
                let id = r + i + 1;
                json!([
                    id as f64,
                    (id % 1_000 + 1) as f64,
                    (id % 97) as f64 + 0.5,
                    format!("Item {id:06}"),
                    REGIONS[id % REGIONS.len()],
                    format!("2026-{:02}-{:02}", 1 + id % 12, 1 + id % 28),
                    format!("K{id:06}"),
                    (id % 1_000) as f64
                ])
            })
            .collect();
        s.execute("range.setValues", json!({"range": format!("A{}", r + 2), "values": values})).map_err(err)?;
        r += n;
    }
    // The props the functions that need one look at, placed in the empty columns to the right of
    // the data: a criteria block for the database functions (a header and a condition), a
    // horizontal table for HLOOKUP, and one formula for FORMULATEXT to print.
    s.execute("range.setValues", json!({"range": "J1", "values": [["Value"], [">0"]]})).map_err(err)?;
    s.execute("range.setValues", json!({"range": "K1", "values": [["Key"], ["K000007"]]})).map_err(err)?;
    s.execute("range.setValues", json!({"range": "M1", "values": [[1.0, 2.0, 3.0, 4.0], [10.0, 20.0, 30.0, 40.0]]})).map_err(err)?;
    s.execute("cell.set", json!({"cell": "Y1", "input": "=SUM(A2:A11)"})).map_err(err)?;
    let doc = s.doc().map_err(err)?.clone();
    Ok(doc)
}

fn measure(base: &DocState, call: &Call, rows: usize, scale: &'static str) -> Result<Measurement, String> {
    let mut s = Session::new();
    s.add_document(base.clone());
    let formula = format!("={}", expand(&call.template, rows, scale));
    let started = Instant::now();
    let entered = s.execute("cell.set", json!({"cell": TARGET, "input": formula}));
    let ms = started.elapsed().as_secs_f64() * 1_000.0;
    let (outcome, detail) = match entered {
        Ok(_) => match s.execute("cell.get", json!({"cell": TARGET})) {
            Ok(v) => match v.get("value") {
                Some(Json::Object(o)) => match o.get("error").and_then(Json::as_str) {
                    Some(code) => ("error", Some(code.to_string())),
                    None => ("ok", None),
                },
                _ => ("ok", None),
            },
            Err(e) => ("ok", Some(format!("value unreadable: {e}"))),
        },
        Err(EngineError::Disabled(_, why)) => ("refused", Some(why)),
        Err(EngineError::BadParams { msg, .. }) => ("refused", Some(msg)),
        Err(EngineError::Internal(_, msg)) => ("refused", Some(format!("panic guard: {msg}"))),
        Err(e) => ("refused", Some(e.to_string())),
    };
    Ok(Measurement {
        name: call.name.clone(),
        template: call.template.clone(),
        rows,
        scale,
        ms,
        expected: call.expect_error && outcome == "error",
        outcome,
        detail,
        note: call.note.clone(),
    })
}

fn report(args: &Args, measurements: &[Measurement], floors: &[(usize, f64)]) -> Json {
    let rows: Vec<Json> = measurements
        .iter()
        .map(|m| {
            let mut o = json!({
                "name": m.name,
                "template": m.template,
                "rows": m.rows,
                "scale": m.scale,
                "ms": m.ms,
                "outcome": m.outcome,
                "expected": m.expected,
            });
            if let Some(d) = &m.detail {
                o["detail"] = json!(d);
            }
            if let Some(n) = &m.note {
                o["note"] = json!(n);
            }
            o
        })
        .collect();
    json!({
        "schema": 1,
        "rows": args.rows,
        "repeat": args.repeat,
        "scales": SCALES,
        "debug": cfg!(debug_assertions),
        "floors": floors.iter().map(|(rows, ms)| json!({"rows": rows, "ms": ms})).collect::<Vec<_>>(),
        "measurements": rows,
    })
}

fn fmt_ms(ms: f64) -> String {
    if ms >= 1_000.0 {
        format!("{:.2} s", ms / 1_000.0)
    } else if ms >= 10.0 {
        format!("{ms:.0} ms")
    } else if ms >= 1.0 {
        format!("{ms:.1} ms")
    } else {
        format!("{:.0} us", ms * 1_000.0)
    }
}

fn render(measurements: &[Measurement]) -> String {
    let mut s = format!("\n{:<28} {:>8} {:>7} {:>9}  {}\n", "function", "rows", "scale", "time", "outcome");
    s += &format!("{:<28} {:>8} {:>7} {:>9}  {}\n", "-".repeat(28), "-".repeat(8), "-".repeat(7), "-".repeat(9), "-".repeat(7));
    for m in measurements {
        let outcome = match &m.detail {
            Some(d) => format!("{}: {d}", m.outcome),
            None => m.outcome.to_string(),
        };
        s += &format!("{:<28} {:>8} {:>7} {:>9}  {}\n", m.name, m.rows, m.scale, fmt_ms(m.ms), outcome);
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_line_is_name_and_template() {
        let calls = parse_calls("# a comment\n\nABS\tABS(1)\nVLOOKUP\tVLOOKUP($K,$T,2,FALSE)\n").expect("parses");
        assert_eq!(calls.len(), 2);
        assert_eq!(calls[1].name, "VLOOKUP");
        assert!(parse_calls("ABS\n").is_err());
    }

    #[test]
    fn tokens_expand_to_the_two_scales() {
        let small = expand("SUM($R)", 1_000_000, "small");
        let whole = expand("SUM($R)", 1_000_000, "whole");
        assert_eq!(small, "SUM(A2:A11)");
        assert_eq!(whole, "SUM(A2:A1000000)");
        assert_eq!(expand("VLOOKUP($K,$T,2,FALSE)", 100, "small"), "VLOOKUP(\"K000007\",G1:H11,2,FALSE)");
    }

    #[test]
    fn longest_token_wins() {
        assert_eq!(expand("$R2", 20, "small"), "B2:B11");
        assert_eq!(expand("$TN", 20, "small"), "A1:C11");
    }

    #[test]
    fn a_template_without_tokens_is_scalar() {
        assert!(!has_token("ABS(1)"));
        assert!(has_token("SUM($R)"));
    }
}
